async function main() {
  let createdRegions = 0;
  let createdDistricts = 0;

  for (const [regionName, districtNames] of Object.entries(regions)) {
    let region = await prisma.region.findUnique({ where: { name: regionName }, select: { id: true } });
    if (!region) {
      region = await prisma.region.create({ data: { id: randomUUID(), name: regionName }, select: { id: true } });
      createdRegions += 1;
    }

    const regionId = region.id;
    const existing = await prisma.district.findMany({ where: { regionId }, select: { name: true } });
    const existingNames = new Set(existing.map((district) => district.name));
    const missing = districtNames.filter((name) => !existingNames.has(name));
    if (missing.length > 0) {
      await prisma.district.createMany({ data: missing.map((name) => ({ id: randomUUID(), name, regionId })) });
      createdDistricts += missing.length;
    }
  }

  console.log(`Regions created: ${createdRegions}, districts created: ${createdDistricts}`);
}

main()
  .catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : 'Unable to seed regions and districts');
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
